param(
    [string]$Source = "$PSScriptRoot/../assets/usagekani/codex-mascot-source.jpg",
    [string]$Output = "$PSScriptRoot/../hal_firmware/Core/Inc/usage_codex_mascot.h"
)

# Deterministic LVGL asset conversion of the user-supplied badge. Matches the
# approved preview's invert(1) contrast(2), rendered white over a dark screen.
# Windows System.Drawing is used only at asset-generation time, never at build.
Add-Type -AssemblyName System.Drawing
$original = [Drawing.Image]::FromFile([IO.Path]::GetFullPath($Source))
$bitmap = [Drawing.Bitmap]::new(92, 94)
$graphics = [Drawing.Graphics]::FromImage($bitmap)
try {
    $graphics.InterpolationMode = [Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
    $graphics.PixelOffsetMode = [Drawing.Drawing2D.PixelOffsetMode]::HighQuality
    $graphics.DrawImage($original, 0, 0, 92, 94)
    $lines = [Collections.Generic.List[string]]::new()
    $lines.Add('/* Generated by scripts/convert_codex_mascot.ps1; do not hand edit. */')
    $lines.Add('#ifndef USAGE_CODEX_MASCOT_H')
    $lines.Add('#define USAGE_CODEX_MASCOT_H')
    $lines.Add('#include "lvgl.h"')
    $lines.Add('static const uint8_t usage_codex_alpha[] = {')
    for ($y = 0; $y -lt 94; $y++) {
        $row = for ($x = 0; $x -lt 92; $x++) {
            $pixel = $bitmap.GetPixel($x, $y)
            $gray = (0.2126 * $pixel.R + 0.7152 * $pixel.G + 0.0722 * $pixel.B) / 255
            $alpha = [int][Math]::Round(255 * [Math]::Clamp(1.5 - 2 * $gray, 0.0, 1.0))
            '0x{0:x2}' -f $alpha
        }
        $lines.Add('    ' + ($row -join ',') + ',')
    }
    $lines.Add('};')
    $lines.Add('static const lv_img_dsc_t usage_codex_mascot = {')
    $lines.Add('    .header = {.cf = LV_IMG_CF_ALPHA_8BIT, .always_zero = 0, .w = 92, .h = 94},')
    $lines.Add('    .data_size = sizeof(usage_codex_alpha), .data = usage_codex_alpha')
    $lines.Add('};')
    $lines.Add('#endif')
    [IO.File]::WriteAllText([IO.Path]::GetFullPath($Output), ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
} finally {
    $graphics.Dispose()
    $bitmap.Dispose()
    $original.Dispose()
}
